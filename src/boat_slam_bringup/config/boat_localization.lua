include "boat_cartographer.lua"


-- ============================================================
-- Cartographer Pure Localization 설정
--
-- 저장된 pbstream 지도:
--   고정된 기준 지도
--
-- 현재 라이다 스캔:
--   기존 지도와 비교하여 현재 위치 계산
--
-- 이 모드에서도 현재 위치추정을 위해 작은 임시 submap은 생기지만,
-- 아래 trimmer가 오래된 임시 submap을 계속 삭제한다.
-- 기존 pbstream 파일 자체는 수정되지 않는다.
-- ============================================================


-- ============================================================
-- Pure Localization Trimmer
--
-- 현재 주행에서 만들어지는 임시 submap을 최대 3개만 유지한다.
--
-- 숫자가 너무 크면:
--   위치추정 중 임시 지도가 많이 쌓임
--
-- 숫자가 너무 작으면:
--   위치추정이 불안정할 수 있음
--
-- 보통 3개가 무난하다.
-- ============================================================
TRAJECTORY_BUILDER.pure_localization_trimmer = {
  max_submaps_to_keep = 3,
}


-- ============================================================
-- 위치추정용 Pose Graph 최적화 주기
--
-- Mapping보다 자주 최적화하여 기존 지도와 현재 스캔의
-- 위치 관계를 빠르게 보정한다.
-- ============================================================
POSE_GRAPH.optimize_every_n_nodes = 20


-- ============================================================
-- 기존 지도 전체에서 현재 위치를 찾을 때 사용하는 최소 점수
--
-- 너무 높으면:
--   위치를 잘 못 찾을 수 있음
--
-- 너무 낮으면:
--   비슷한 구조에 잘못 붙을 수 있음
--
-- 기존 boat_cartographer.lua 값보다 위치추정에 적합하게 조정
-- ============================================================
POSE_GRAPH.constraint_builder.global_localization_min_score = 0.60


-- ============================================================
-- 일반 스캔 매칭 최소 점수
-- ============================================================
POSE_GRAPH.constraint_builder.min_score = 0.55


-- ============================================================
-- 위치추정에서는 기존 frozen map과 현재 trajectory 사이의
-- global constraint 후보를 충분히 검사해야 한다.
-- ============================================================
POSE_GRAPH.global_sampling_ratio = 0.10


-- ============================================================
-- 위치추정 시 최종 반복 횟수
-- ============================================================
POSE_GRAPH.max_num_final_iterations = 50


return options
